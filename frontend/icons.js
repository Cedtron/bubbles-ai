function icon(name, extraClass) {
  const inner = ICON_PATHS[name];
  if (!inner) return "";
  const cls = "icon" + (extraClass ? " " + extraClass : "");
  return `<svg class="${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>`;
}

/**
 * Replaces every <span data-icon="name"></span> found in the page
 * with the actual SVG markup. Called once on init, and again any
 * time new icon placeholders are injected dynamically.
 */
function renderIconPlaceholders(root) {
  const scope = root || document;
  scope.querySelectorAll("[data-icon]").forEach((el) => {
    const name = el.getAttribute("data-icon");
    const size = el.getAttribute("data-icon-size");
    el.innerHTML = icon(name, size ? "icon-" + size : "");
  });
}
